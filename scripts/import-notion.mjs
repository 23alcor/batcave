#!/usr/bin/env node
// Optional: pull your Notion databases through the Notion API and write seed/notion-import.sql
// (upserts keyed on Notion page ids), then load it with:
//   npx wrangler d1 execute batcave --remote --file seed/notion-import.sql
//
// Setup:
//   1. Create an internal integration at https://www.notion.so/profile/integrations and connect it to the
//      pages that hold your databases (••• menu → Connections).
//   2. Copy scripts/notion.config.example.json to scripts/notion.config.json (git-ignored) and paste the
//      data source id of each database you want to import. Leave out the ones you don't have.
//   3. NOTION_TOKEN=ntn_xxx node scripts/import-notion.mjs [--only=links,tasks,...]
//
// The property names below ("Due", "Status", "Project"…) match the author's Notion setup. If yours are
// named differently, change them in the matching section further down.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const TOKEN = process.env.NOTION_TOKEN;
if (!TOKEN) { console.error('Set NOTION_TOKEN first.'); process.exit(1); }
const CONFIG = new URL('./notion.config.json', import.meta.url);
if (!existsSync(CONFIG)) { console.error('Copy scripts/notion.config.example.json to scripts/notion.config.json and fill in your database ids.'); process.exit(1); }
const DS = Object.fromEntries(Object.entries(JSON.parse(readFileSync(CONFIG, 'utf8'))).filter(([k, v]) => typeof v === 'string' && /^[0-9a-f-]{32,36}$/i.test(v) && !/^[0-]+$/.test(v)));
const only = (process.argv.find((a) => a.startsWith('--only=')) || '').slice(7).split(',').filter(Boolean);
const want = (k) => (!only.length || only.includes(k)) && Boolean(DS[k]);

// Your time zone: TIMEZONE env var, else the TIMEZONE var in wrangler.jsonc, else New York.
function timezone() {
  if (process.env.TIMEZONE) return process.env.TIMEZONE;
  try {
    const raw = readFileSync(new URL('../wrangler.jsonc', import.meta.url), 'utf8').replace(/^\s*\/\/.*$/gm, '').replace(/,(\s*[}\]])/g, '$1');
    return JSON.parse(raw).vars?.TIMEZONE || 'America/New_York';
  } catch { return 'America/New_York'; }
}
const TZ = timezone();

async function query(dsId) {
  const rows = [];
  let cursor;
  do {
    const r = await fetch(`https://api.notion.com/v1/data_sources/${dsId}/query`, {
      method: 'POST',
      headers: { authorization: `Bearer ${TOKEN}`, 'notion-version': '2025-09-03', 'content-type': 'application/json' },
      body: JSON.stringify({ page_size: 100, ...(cursor ? { start_cursor: cursor } : {}) }),
    });
    if (!r.ok) throw new Error(`${dsId}: ${r.status} ${await r.text()}`);
    const j = await r.json();
    rows.push(...j.results.filter((p) => !p.in_trash && !p.archived));
    cursor = j.has_more ? j.next_cursor : null;
  } while (cursor);
  return rows;
}

const id = (p) => p.id.replace(/-/g, '');
const text = (rt) => (rt || []).map((t) => t.plain_text).join('').trim();
const prop = (p, name) => p.properties[name];
const title = (p) => { const t = Object.values(p.properties).find((x) => x.type === 'title'); return t ? text(t.title) : ''; };
const checkbox = (p, n) => (prop(p, n)?.checkbox ? 1 : 0);
const num = (p, n) => prop(p, n)?.number ?? null;
const sel = (p, n) => prop(p, n)?.select?.name ?? prop(p, n)?.status?.name ?? null;
const rel = (p, n) => (prop(p, n)?.relation || []).map((r) => r.id.replace(/-/g, ''));
const plain = (p, n) => text(prop(p, n)?.rich_text);
const url = (p, n) => prop(p, n)?.url || null;
const firstOfType = (p, type) => Object.values(p.properties).find((x) => x.type === type);

// Notion dates → local wall clock in TZ ('YYYY-MM-DD' or 'YYYY-MM-DDTHH:MM')
function localWall(start) {
  if (!start) return null;
  if (start.length === 10) return start;
  const d = new Date(start);
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false }).formatToParts(d);
  const g = (t) => parts.find((x) => x.type === t).value;
  return `${g('year')}-${g('month')}-${g('day')}T${g('hour') === '24' ? '00' : g('hour')}:${g('minute')}`;
}
const date = (p, n) => localWall(prop(p, n)?.date?.start);

const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const upsert = (table, row, keep = []) => {
  const cols = Object.keys(row);
  const updates = cols.filter((c) => c !== 'id' && !keep.includes(c)).map((c) => `${c}=excluded.${c}`).join(', ');
  return `INSERT INTO ${table} (${cols.join(',')}) VALUES (${cols.map((c) => q(row[c])).join(',')}) ON CONFLICT(id) DO UPDATE SET ${updates};`;
};

const out = ['-- Generated by scripts/import-notion.mjs. Contains personal data: do not commit.', 'PRAGMA defer_foreign_keys = true;'];
const report = {};

if (want('projects')) {
  const rows = await query(DS.projects);
  for (const p of rows) out.push(upsert('projects', { id: id(p), name: title(p), status: sel(p, 'Status'), notion_id: id(p) }, ['short_name', 'color', 'sort']));
  report.projects = rows.length;
}
if (want('tasks')) {
  const rows = await query(DS.tasks);
  let n = 0;
  for (const p of rows) {
    const status = sel(p, 'Status');
    let t = title(p);
    const tbd = /UNCERTAIN DATE/i.test(t) ? 1 : 0;
    t = t.replace(/UNCERTAIN DATE\s*/i, '').trim();
    const done = ['Done', 'Cancelled', 'Archived'].includes(status);
    out.push(upsert('tasks', {
      id: id(p), title: t, project_id: rel(p, 'Projects')[0] || null, kind: 'task',
      due_at: tbd ? null : date(p, 'Action Date'), date_tbd: tbd, status: done ? (status === 'Done' ? 'done' : 'cancelled') : 'open',
      url: url(p, 'URL'), notion_id: id(p),
    }));
    n++;
  }
  report.tasks = n;
}
if (want('todo')) {
  const rows = await query(DS.todo);
  let n = 0;
  for (const p of rows) {
    const status = sel(p, 'Status');
    if (status === 'Daily') continue; // habits live in the habits table
    out.push(upsert('tasks', {
      id: id(p), title: title(p) || '(untitled)', kind: 'inbox', due_at: date(p, 'Date Due'),
      status: status === 'Done' || checkbox(p, 'Done') ? 'done' : 'open', notes: plain(p, 'Text') || null, notion_id: id(p),
    }));
    n++;
  }
  report.inbox = n;
}
if (want('links')) {
  const rows = await query(DS.links);
  for (const p of rows) {
    const u = url(p, 'URL');
    if (!u) continue;
    out.push(upsert('links', { id: id(p), title: title(p) || u, url: u, added_on: date(p, 'Date Added') || p.created_time.slice(0, 10), done: checkbox(p, 'Done'), needs_manual: checkbox(p, 'Needs manual'), notion_id: id(p) }));
  }
  report.links = rows.length;
}
if (want('garage')) {
  const cars = await query(DS.garage);
  for (const p of cars) {
    out.push(upsert('vehicles', { id: id(p), name: title(p), plate: plain(p, 'License Plate') || null, vin: plain(p, 'VIN') || null, mileage: num(p, 'Current Mileage'), purchase_date: date(p, 'Purchase Date'), purchase_price: num(p, 'Purchase Price'), notion_id: id(p) }));
  }
  const carIds = new Set(cars.map(id));
  for (const [kind, ds] of [['maintenance', DS.maintenance], ['ticket', DS.tickets], ['insurance', DS.insurance]].filter(([, ds]) => ds)) {
    let rows = [];
    try { rows = await query(ds); } catch (e) { console.warn(`skipping ${kind}: ${e.message.slice(0, 120)}`); continue; }
    for (const p of rows) {
      const relProp = Object.values(p.properties).find((x) => x.type === 'relation' && x.relation.some((r) => carIds.has(r.id.replace(/-/g, ''))));
      const vehicle = relProp ? relProp.relation.map((r) => r.id.replace(/-/g, '')).find((r) => carIds.has(r)) : null;
      if (!vehicle) continue;
      const d = firstOfType(p, 'date');
      const costProp = Object.entries(p.properties).find(([k, v]) => v.type === 'number' && /cost|price|amount|total|fine|premium/i.test(k));
      out.push(upsert('vehicle_logs', { id: id(p), vehicle_id: vehicle, kind, day: localWall(d?.date?.start)?.slice(0, 10) || null, title: title(p) || kind, cost: costProp ? costProp[1].number : null, notion_id: id(p) }));
      if (kind === 'insurance' && d?.date?.end) out.push(`UPDATE vehicles SET insurance_until = ${q(d.date.end.slice(0, 10))} WHERE id = ${q(vehicle)};`);
    }
    report[kind] = rows.length;
  }
  report.vehicles = cars.length;
}
if (want('wishlist')) {
  const rows = await query(DS.wishlist);
  for (const p of rows) {
    out.push(upsert('wishlist', { id: id(p), name: title(p) || '(untitled)', category: sel(p, 'Category'), status: sel(p, 'Status') || 'Searching', priority: sel(p, 'Priority'), price: num(p, 'Price'), link: url(p, 'Link'), notes: plain(p, 'Text') || null, acquired_on: date(p, 'Acquisition'), notion_id: id(p) }));
  }
  report.wishlist = rows.length;
}

mkdirSync('seed', { recursive: true });
writeFileSync('seed/notion-import.sql', out.join('\n') + '\n');
console.log('Wrote seed/notion-import.sql', report);
